import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const sourcePath = path.join(root, 'docs/reverse-engineering/ground-truth/manifests/task-settings-170b1-equipment-page.json');
const outputPath = path.join(root, 'src/generated/EquipmentPageTruth.generated.ts');
const source = readFileSync(sourcePath, 'utf8');
const manifest = JSON.parse(source);
const hash = createHash('sha256').update(source).digest('hex');
const stateIds = manifest.states.map(({ id }) => id);

const objects = manifest.displayObjects.map((item) => {
  const base = item.placements[0];
  for (const placement of item.placements.slice(1)) {
    for (const field of ['localMatrix', 'stageBounds', 'hitArea']) {
      if (JSON.stringify(placement[field] ?? null) !== JSON.stringify(base[field] ?? null)) {
        throw new Error(`${item.id} changes ${field} across states; runtime projection must retain that variation.`);
      }
    }
  }
  return {
    id: item.id,
    parentId: item.parentId,
    depth: item.depth,
    objectType: item.objectType,
    localMatrix: base.localMatrix,
    stageBounds: base.stageBounds,
    ...(base.hitArea ? { hitArea: base.hitArea } : {}),
    visibleStateIds: item.placements.filter(({ visible }) => visible).map(({ stateId }) => stateId),
  };
});

const projection = {
  sourceManifestSha256: hash,
  truthId: manifest.truthId,
  status: manifest.status,
  stage: manifest.stage,
  stateIds,
  displayListMatched: manifest.completeness.displayListMatched,
  stateSetMatched: manifest.completeness.stateSetMatched,
  unresolvedCount: manifest.completeness.unresolved.length,
  objects,
};
const generated = `// Generated by tools/generate-equipment-page-runtime-truth.mjs. Do not edit.\n`
  + `export const EquipmentPageRuntimeTruth = ${JSON.stringify(projection, null, 2)} as const;\n`;

if (process.argv.includes('--check')) {
  if (readFileSync(outputPath, 'utf8') !== generated) {
    throw new Error('Equipment page runtime truth projection is stale. Run npm run generate:equipment-page-runtime-truth.');
  }
  console.log(`Equipment page runtime truth projection matches ${hash}.`);
} else {
  writeFileSync(outputPath, generated);
  console.log(`Generated equipment page runtime truth projection from ${hash}.`);
}
