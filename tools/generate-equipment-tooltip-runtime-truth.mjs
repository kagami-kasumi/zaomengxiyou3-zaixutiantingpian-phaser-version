import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const sourcePath = path.join(root, 'docs/reverse-engineering/ground-truth/manifests/task-settings-189-equipment-tooltip.json');
const outputPath = path.join(root, 'src/generated/EquipmentTooltipTruth.generated.ts');
const source = readFileSync(sourcePath, 'utf8');
const manifest = JSON.parse(source);
const hash = createHash('sha256').update(source).digest('hex');

const objects = manifest.displayObjects.map((item) => {
  const visiblePlacement = item.placements.find(({ visible }) => visible);
  return {
    id: item.id,
    parentId: item.parentId,
    depth: item.depth,
    objectType: item.objectType,
    ...(visiblePlacement ? { localMatrix: visiblePlacement.localMatrix } : {}),
    ...(item.render?.textStyle ? { textStyle: item.render.textStyle } : {}),
    filters: item.render?.filters ?? [],
  };
});

const projection = {
  sourceManifestSha256: hash,
  truthId: manifest.truthId,
  status: manifest.status,
  stage: manifest.stage,
  stateIds: manifest.states.map(({ id }) => id),
  displayListMatched: manifest.completeness.displayListMatched,
  stateSetMatched: manifest.completeness.stateSetMatched,
  unresolvedCount: manifest.completeness.unresolved.length,
  fixtureRootBoundsByState: Object.fromEntries(
    manifest.displayObjects.find(({ id }) => id === 'tooltip-root').placements.map(
      ({ stateId, stageBounds }) => [stateId, stageBounds],
    ),
  ),
  objects,
};
const generated = `// Generated by tools/generate-equipment-tooltip-runtime-truth.mjs. Do not edit.\n`
  + `export const EquipmentTooltipRuntimeTruth = ${JSON.stringify(projection, null, 2)} as const;\n`;

if (process.argv.includes('--check')) {
  if (readFileSync(outputPath, 'utf8') !== generated) {
    throw new Error('Equipment tooltip runtime truth projection is stale. Run npm run generate:equipment-tooltip-runtime-truth.');
  }
  console.log(`Equipment tooltip runtime truth projection matches ${hash}.`);
} else {
  writeFileSync(outputPath, generated);
  console.log(`Generated equipment tooltip runtime truth projection from ${hash}.`);
}
